/** Reconciled QA regressions. Owns an ephemeral loopback DB; no real tenant writes. */
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { PGlite } from "@electric-sql/pglite";
import { PGLiteSocketServer } from "@electric-sql/pglite-socket";
import { TENANT_TABLES_SQL, TENANT_FKS_SQL, DOCS_HARDENING_SQL } from "../src/lib/tenant-template";

async function main() {
  const pg = await PGlite.create();
  await pg.exec(TENANT_TABLES_SQL + "\n" + TENANT_FKS_SQL + "\n" + DOCS_HARDENING_SQL);
  const socket = new PGLiteSocketServer({ db: pg, host: "127.0.0.1", port: 0, maxConnections: 10 });
  await socket.start();
  process.env.DATABASE_URL = `postgresql://postgres@${socket.getServerConn()}/postgres`;
  process.env.DIRECT_URL = process.env.DATABASE_URL;
  process.env.DATABASE_POOL_MAX = "1";
  process.env.DEMO_MODE = "1";
  process.env.DEMO_USER_ROLE = "ADMIN";
  process.env.DEMO_POOL_SIZE = "2";
  globalThis.fetch = async () => { throw new Error("External networking disabled in QA regressions"); };
  const { prisma: p } = await import("../src/lib/db");
  const g = await import("../src/lib/services/gaap");
  const a = await import("../src/app/actions");
  const s = await import("../src/lib/services/supply-chain");
  const ri = await import("../src/lib/services/receiving-inspection");
  const rv = await import("../src/lib/services/receiving");
  const form = (values: Record<string,string>) => { const f = new FormData(); for (const [k,v] of Object.entries(values)) f.set(k,v); return f; };
  const action = async (fn: (f: FormData) => Promise<void>, values: Record<string,string>) => { try { await fn(form(values)); } catch (e) { if (!/NEXT_REDIRECT|outside.*request|incrementalCache|static generation store/i.test(String(e))) throw e; } };
  try {
    const admin = await p.user.create({ data: { name: "Admin", email: "qa-admin@example.invalid", role: "ADMIN" } });
    const operator = await p.user.create({ data: { name: "Operator", email: "qa-operator@example.invalid", role: "OPERATOR" } });
    const approver = await p.user.create({ data: { name: "Approver", email: "qa-approve@example.invalid", role: "EXECUTIVE" } });
    const cash = await p.account.create({ data: { code: "1000", name: "Cash", type: "ASSET" } });
    const ar = await p.account.create({ data: { code: "1100", name: "AR", type: "ASSET" } });
    await p.account.create({ data: { code: "2000", name: "AP", type: "LIABILITY" } });
    await p.accountingSettings.create({ data: { id: "default", requireJournalSoD: true } });
    const balance = async () => (await p.account.findUniqueOrThrow({ where: { id: cash.id } })).balance;
    const pending = () => g.postJournal({ description: "Concurrent approval", createdById: admin.id, lines: [{ accountId: cash.id, debit: 10 }, { accountId: ar.id, credit: 10 }] });
    const j = await pending();
    await Promise.all(Array.from({ length: 6 }, () => g.approveJournal({ id: j.id, approvedById: approver.id })));
    assert.equal(await balance(), 10);
    await g.approveJournal({ id: j.id, approvedById: approver.id });
    assert.equal(await balance(), 10);
    console.log("PASS ACCT-006 six competing approvals and retry apply balances exactly once");
    const fail = await pending();
    await pg.exec(`CREATE FUNCTION qa_fail_balance() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'qa injected balance failure'; END $$; CREATE TRIGGER qa_fail_balance BEFORE UPDATE ON "Account" FOR EACH ROW EXECUTE FUNCTION qa_fail_balance();`);
    await assert.rejects(g.approveJournal({ id: fail.id, approvedById: approver.id }), /qa injected balance failure/);
    assert.equal((await p.journalEntry.findUniqueOrThrow({ where: { id: fail.id } })).status, "PENDING_APPROVAL");
    assert.equal(await balance(), 10);
    await pg.exec('DROP TRIGGER qa_fail_balance ON "Account"; DROP FUNCTION qa_fail_balance();');
    await g.approveJournal({ id: fail.id, approvedById: approver.id });
    assert.equal(await balance(), 20);
    console.log("PASS ACCT-006 failed balance application rolls back claim and can retry");
    process.env.DEMO_USER_ROLE = "EXECUTIVE";
    const approvedOnly = await pending();
    await action(a.actionApproveJournal, { id: approvedOnly.id });
    assert.equal((await p.journalEntry.findUniqueOrThrow({ where: { id: approvedOnly.id } })).status, "POSTED");
    process.env.DEMO_USER_ROLE = "OPERATOR";
    const denied = await pending();
    await assert.rejects(a.actionApproveJournal(form({ id: denied.id })), /Not authorized/);
    const perm = await p.permission.create({ data: { code: "accounting.journal.post", name: "Post", module: "accounting" } });
    await p.userPermission.create({ data: { userId: operator.id, permissionId: perm.id, allowed: true } });
    await assert.rejects(a.actionApproveJournal(form({ id: denied.id })), /Not authorized/);
    assert.equal((await p.journalEntry.findUniqueOrThrow({ where: { id: denied.id } })).status, "PENDING_APPROVAL");
    console.log("PASS ACCT-007 approval-only executive succeeds; posting-only grant does not approve");
    process.env.DEMO_USER_ROLE = "ADMIN";
    const supplier = await p.supplier.create({ data: { code: "QA", name: "QA supplier", isApprovedVendor: true } });
    const wh = await p.warehouse.create({ data: { code: "QA", name: "QA" } });
    const loc = await p.location.create({ data: { warehouseId: wh.id, code: "STOCK", type: "STORAGE" } });
    await p.location.create({ data: { warehouseId: wh.id, code: "RCV-01", type: "RECEIVING" } });
    let seq = 0;
    async function fixture(flags = {}, qty = 2) {
      const n = ++seq;
      const part = await p.part.create({ data: { partNumber: "QA-" + n, description: "QA part", standardCost: 10, ...flags } });
      const po = await p.purchaseOrder.create({ data: { number: "PO-QA-" + n, supplierId: supplier.id, status: "APPROVED", lines: { create: { partId: part.id, description: "QA", quantity: qty, unitCost: 10 } } }, include: { lines: true } });
      const traveler = await rv.createReceivingTravelerForPo({ purchaseOrderId: po.id, userId: admin.id });
      return { part, po, traveler };
    }
    type Fixture = Awaited<ReturnType<typeof fixture>>;
    const receive = (x: Fixture, serialNumbers?: string[], quantityReceived = 2) => s.receivePurchaseOrder({ purchaseOrderId: x.po.id, travelerId: x.traveler.id, receivedById: admin.id, receivingAck: true, putawayLocationCode: loc.code, packingListDocs: [{ url: "/qa/packing.pdf" }], cocDocs: [{ url: "/qa/coc.pdf" }], lines: [{ poLineId: x.po.lines[0].id, quantityReceived, serialNumbers }] });
    for (const serials of [undefined, ["ONE"], ["DUP", " dup "], [" ", "TWO"]]) {
      const x = await fixture({ isSerialized: true });
      const before = await p.receipt.count();
      await assert.rejects(receive(x, serials), /serial/i);
      assert.equal(await p.receipt.count(), before);
      assert.equal((await p.purchaseOrderLine.findUniqueOrThrow({ where: { id: x.po.lines[0].id } })).quantityReceived, 0);
    }
    const fractional = await fixture({ isSerialized: true });
    await assert.rejects(receive(fractional, ["FRACTION"], 1.2), /whole unit/);
    const good = await fixture({ isSerialized: true });
    await receive(good, [" first ", "second"]);
    const ss = await import("../src/lib/services/stock-serials");
    assert.deepEqual((await ss.listStockSerialsForParts([good.part.id])).map(x => x.serial), ["FIRST", "SECOND"]);
    const duplicate = await fixture({ isSerialized: true });
    const before = await p.receipt.count();
    await assert.rejects(receive(duplicate, ["FIRST", "NEW"]), /already exists/);
    assert.equal(await p.receipt.count(), before);
    assert.equal(await p.serialNumber.count({ where: { serial: "NEW" } }), 0);
    console.log("PASS SERIAL-001/002 canonical, unique one-per-unit receiving; stock identities and rollback on duplicate");
    const qc = await fixture({ isSerialized: true, requiresGdtInspection: true });
    await receive(qc, ["QA-S1", "QA-S2"]);
    assert.equal((await ss.listStockSerialsForParts([qc.part.id])).length, 0);
    const ins = await p.inspection.findFirstOrThrow({ where: { purchaseOrderId: qc.po.id } });
    process.env.DEMO_USER_ROLE = "OPERATOR";
    await assert.rejects(a.actionCompleteReceivingInspection(form({ inspectionId: ins.id, result: "PASS", doc_0: "/qa/evidence.pdf" })), /Not authorized/);
    assert.equal((await p.inspection.findUniqueOrThrow({ where: { id: ins.id } })).status, "PENDING");
    process.env.DEMO_USER_ROLE = "ADMIN";
    for (const row of await p.inspection.findMany({ where: { purchaseOrderId: qc.po.id } })) await ri.completeReceivingInspection({ inspectionId: row.id, result: "PASS", documents: [{ url: "/qa/evidence.pdf" }], userId: admin.id });
    for (const tr of await p.receivingTraveler.findMany({ where: { purchaseOrderId: qc.po.id, status: "READY_TO_STOCK" } })) await ri.completeReceivingAfterInspection({ travelerId: tr.id, putawayLocationCode: loc.code, userId: admin.id });
    assert.equal((await ss.listStockSerialsForParts([qc.part.id])).length, 2);
    console.log("PASS AUTH-005 operator inspection action denied; approved serials only selectable after QA putaway");
    const bad = await fixture({ requiresGdtInspection: true }, 5);
    await receive(bad, undefined, 5);
    const insp = await p.inspection.findFirstOrThrow({ where: { purchaseOrderId: bad.po.id } });
    await ri.completeReceivingInspection({ inspectionId: insp.id, result: "FAIL", documents: [{ url: "/qa/failed.pdf" }], userId: admin.id });
    const ncr = await p.nonConformance.findFirstOrThrow({ where: { inspectionId: insp.id } });
    const mrb = await p.mrbCase.findFirstOrThrow({ where: { ncrId: ncr.id } });
    const original = await p.inventoryItem.findFirstOrThrow({ where: { mrbCaseId: mrb.id } });
    await p.inventoryItem.update({ where: { id: original.id }, data: { quantityOnHand: 1, quantityQuarantine: 1 } });
    await p.inventoryItem.create({ data: { partId: bad.part.id, locationId: original.locationId, quantityOnHand: 4, quantityQuarantine: 4, mrbCaseId: mrb.id } });
    await s.dispositionMrb({ mrbCaseId: mrb.id, disposition: "SCRAP", quantity: 2, justification: "Two of five", decidedById: admin.id });
    assert.equal((await p.inventoryItem.aggregate({ where: { partId: bad.part.id }, _sum: { quantityOnHand: true, quantityQuarantine: true } }))._sum.quantityOnHand, 3);
    assert.equal((await p.materialTransaction.aggregate({ where: { reference: mrb.number, type: "SCRAP" }, _sum: { quantity: true } }))._sum.quantity, 2);
    assert.equal((await p.mrbCase.findUniqueOrThrow({ where: { id: mrb.id } })).status, "OPEN");
    assert.equal((await p.inventoryItem.aggregate({ where: { mrbCaseId: mrb.id }, _sum: { quantityQuarantine: true } }))._sum.quantityQuarantine, 3);
    await assert.rejects(s.dispositionMrb({ mrbCaseId: mrb.id, disposition: "SCRAP", quantity: 4, justification: "Too many" }), /exceeds/);
    for (const quantity of [-1, 0, Infinity, NaN]) await assert.rejects(s.dispositionMrb({ mrbCaseId: mrb.id, disposition: "SCRAP", quantity, justification: "Invalid" }), /positive/);
    await s.dispositionMrb({ mrbCaseId: mrb.id, disposition: "SCRAP", quantity: 3, justification: "Remaining three" });
    await assert.rejects(s.dispositionMrb({ mrbCaseId: mrb.id, disposition: "SCRAP", quantity: 3, justification: "Repeat" }), /already/);
    console.log("PASS MRB-001/002/003 partial multi-hold scrap conserves quantity, keeps remainder held and rejects invalid/repeat decisions");
    // An RMA tear-down holds a serial, not necessarily an InventoryItem row.
    const serialNcr = await p.nonConformance.create({ data: { number: "NCR-SERIAL", title: "Serial tear-down", source: "CUSTOMER", partId: good.part.id, quantity: 1, description: "RMA tear-down" } });
    const stockSerial = await p.serialNumber.findUniqueOrThrow({ where: { serial: "FIRST" } });
    const serialMrb = await p.mrbCase.create({ data: { number: "MRB-SERIAL", ncrId: serialNcr.id, serialId: stockSerial.id } });
    await s.dispositionMrb({ mrbCaseId: serialMrb.id, disposition: "SCRAP", quantity: 1, justification: "Unrepairable serial" });
    assert.equal((await p.serialNumber.findUniqueOrThrow({ where: { id: stockSerial.id } })).status, "SCRAPPED");
    assert.equal((await p.mrbCase.findUniqueOrThrow({ where: { id: serialMrb.id } })).status, "DISPOSITIONED");
    console.log("PASS MRB serial-only RMA tear-down remains scrappable without a stock hold");
    // Clone a template only in this disposable database, then race real refills.
    const raw = execFileSync("node", ["node_modules/prisma/build/index.js", "migrate", "diff", "--from-empty", "--to-schema", "prisma/schema.prisma", "--script"], { encoding: "utf8", maxBuffer: 8 * 1024 * 1024, stdio: ["ignore", "pipe", "pipe"] });
    const tenantDdl = raw.match(/CREATE TABLE "Tenant" \([\s\S]*?\n\);/)?.[0];
    assert(tenantDdl);
    await pg.exec(tenantDdl);
    const t = await import("../src/lib/services/tenancy");
    await t.cloneSchema("public", "demo_template");
    const made = await Promise.all([t.ensureDemoPool(), t.ensureDemoPool(), t.ensureDemoPool()]);
    assert.equal(made.reduce((x,y) => x+y, 0), 2);
    assert.equal(await p.tenant.count({ where: { isDemo: true, status: "READY" } }), 2);
    assert.equal(await t.ensureDemoPool(), 0);
    process.env.DEMO_POOL_SIZE = "0";
    assert.equal(await t.ensureDemoPool(), 0);
    console.log("PASS DEMO-001 three competing refills produce exactly two spares; target and disabled pool respected");
  } finally { await p.$disconnect(); await socket.stop(); await pg.close(); }
}
main().catch(e => { console.error(e); process.exitCode = 1; });
